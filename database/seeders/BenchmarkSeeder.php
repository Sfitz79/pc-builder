    public function run(): void
    {
        // FPS data keyed by cpu_chipset -> gpu_chipset -> resolution -> game => fps
        // Sources: TechSpot, GamersNexus, HardwareUnboxed, PCWorld benchmarks (2025-2026)
        // All tested at Ultra/High settings unless noted. Values are average FPS.
        $data = $this->benchmarkData();

        $resolvedCpu = [];
        $resolvedGpu = [];

        foreach ($data as $cpuChipset => $gpus) {
            if (! isset($resolvedCpu[$cpuChipset])) {
                $cpu = Component::where('chipset', $cpuChipset)->where('category_id', 1)->first();
                $resolvedCpu[$cpuChipset] = $cpu?->id;
            }
            $cpuId = $resolvedCpu[$cpuChipset];
            if (! $cpuId) {
                continue;
            }

            foreach ($gpus as $gpuChipset => $resolutions) {
                if (! isset($resolvedGpu[$gpuChipset])) {
                    $gpu = Component::where('chipset', $gpuChipset)->where('category_id', 4)->first();
                    $resolvedGpu[$gpuChipset] = $gpu?->id;
                }
                $gpuId = $resolvedGpu[$gpuChipset];
                if (! $gpuId) {
                    continue;
                }

                foreach ($resolutions as $resolution => $games) {
                    foreach ($games as $game => $fps) {
                        Benchmark::updateOrCreate(
                            [
                                'cpu_id' => $cpuId,
                                'gpu_id' => $gpuId,
                                'game' => $game,
                                'resolution' => $resolution,
                            ],
                            [
                                'fps' => $fps,
                                'settings' => 'Ultra',
                            ]
                        );
                    }
                }
            }
        }
    }

